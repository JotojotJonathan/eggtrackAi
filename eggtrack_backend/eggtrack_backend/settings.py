def get_lan_ip():
    """Get the local network IP of this machine"""
    try:
        # Connect to a public DNS server temporarily to find local network interface
        s = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
        s.connect(('8.8.8.8', 80))
        ip = s.getsockname()[0]
        s.close()
        return ip
    except Exception:
        return None

